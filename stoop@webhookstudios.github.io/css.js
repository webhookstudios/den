// Builds the lock screen stylesheet from our settings. Every rule starts
// with `.unlock-dialog.lm-on`, a marker class the extension adds, so the
// rules outrank the theme's and vanish with the marker.

const SCOPE = '.unlock-dialog.lm-on';

function rgba(hex, alpha) {
    const m = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})/i.exec(hex ?? '');
    const [r, g, b] = m ? [parseInt(m[1], 16), parseInt(m[2], 16), parseInt(m[3], 16)] : [0, 0, 0];
    return `rgba(${r}, ${g}, ${b}, ${Math.max(0, Math.min(1, alpha)).toFixed(3)})`;
}

export function buildCss(v) {
    const rules = [];
    const add = (selector, body) =>
        rules.push(`${selector} {\n${body.filter(Boolean).map(l => `  ${l}`).join('\n')}\n}`);

    const color = rgba(v('clock-color'), v('clock-opacity'));
    const family = v('clock-font').trim().replace(/["\;{}]/g, '');
    const shadow = v('clock-shadow') ? 'text-shadow: 0px 2px 14px rgba(0, 0, 0, 0.55);' : 'text-shadow: none;';
    const text = [`color: ${color};`, family ? `font-family: "${family}";` : '', shadow];

    // The stock clock is replaced by ours; keep it from flashing up before
    // the extension has had a chance to hide it.
    add('.unlock-dialog-clock .unlock-dialog-clock-time, .unlock-dialog-clock .unlock-dialog-clock-date, ' +
        '.unlock-dialog-clock .unlock-dialog-clock-hint', ['color: rgba(0, 0, 0, 0) !important;']);

    add(`${SCOPE} .lm-time`, [
        ...text,
        `font-size: ${v('clock-size')}px;`,
        `font-weight: ${v('clock-weight')} !important;`,
        'font-feature-settings: "tnum";',
    ]);
    add(`${SCOPE} .lm-date`, [
        ...text,
        `font-size: ${v('date-size')}px;`,
        `font-weight: ${v('date-weight')} !important;`,
    ]);
    add(`${SCOPE} .lm-message`, [
        ...text,
        `font-size: ${v('message-size')}px;`,
        'font-weight: 400 !important;',
    ]);
    add(`${SCOPE} .lm-hint`, [
        `color: ${rgba(v('clock-color'), 0.8)};`,
        'font-size: 14px;',
        'font-weight: 500 !important;',
    ]);

    // Password prompt.
    const entry = [
        `border-radius: ${v('entry-radius')}px !important;`,
        `background-color: ${rgba(v('entry-color'), v('entry-opacity'))} !important;`,
        `color: ${rgba(v('entry-text-color'), 1)} !important;`,
    ];
    add(`${SCOPE} StEntry, ${SCOPE} StEntry:focus, ${SCOPE} StEntry:hover`, entry);
    add(`${SCOPE} StEntry StLabel.hint-text`, [`color: ${rgba(v('entry-text-color'), 0.7)} !important;`]);
    add(`${SCOPE} .user-widget.vertical .user-icon`, [`icon-size: ${v('avatar-size')}px;`]);
    add(`${SCOPE} .user-widget .user-widget-label`, [`color: ${rgba(v('entry-text-color'), 1)};`]);

    return `/* Generated by Stoop. Do not edit. */\n${rules.join('\n\n')}\n`;
}
